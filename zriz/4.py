v = input("Введіть швидкість (км/год):")
t = input("Введіть час (год):")
if v.isdigit() == False or t.isdigit() == False:
    print("Введені дані не є коректними числами!")
    exit()
v = int(v)
t = int(t)
s = v*t
print(f"Відстань: {s} кілометрів (обчислюємо по формулі Відстань = Швидкість * Час) ")
print(f"Відстань: {s*1000} метрів (1 кілометр = 1000 метрів) (обчислюємо по формулі Відстань = Швидкість * Час) ")